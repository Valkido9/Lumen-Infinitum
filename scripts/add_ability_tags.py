INDEX_HTML = r"E:\永恒流光\永恒流光\index.html"

with io.open(INDEX_HTML, "r", encoding="utf-8", newline="") as f:
    content = f.read()

count = 0
missing = []

def inject_tg(m):
    global count
    abid = m.group(1)
    if abid in TG:
        count += 1
        return '{id:"%s",tg:"%s"' % (abid, TG[abid])  # 原文本的逗号(如 ,n:)保留，不重复添加
    missing.append(abid)
    return m.group(0)

# 仅在能力档案数据区（abilityData 数组）内注入，避免误伤 characters 等其他对象
# 定位 abilityData 起始行到 abilityTimelines 之前
start = content.find("const abilityData")
end = content.find("const abilityTimelines")
if start == -1 or end == -1 or end < start:
    sys.exit("FATAL: 找不到 abilityData / abilityTimelines 边界")
region = content[start:end]
region_new = re.sub(r'\{id:"(ab\d+)"', inject_tg, region)
content = content[:start] + region_new + content[end:]

with io.open(INDEX_HTML, "w", encoding="utf-8", newline="") as f:
    f.write(content)

print("注入完成: %d / %d" % (count, len(TG)))
if missing:
    print("未匹配到（不在 abilityData 中）: %s" % ", ".join(missing))
