def p(text, style="Normal", bold_runs=None, italic_runs=None):
    """生成一个段落XML。bold_runs/italic_runs 是 (start, end) 索引列表"""
    runs_xml = ""
    if bold_runs is None:
        bold_runs = []
    if italic_runs is None:
        italic_runs = []

    # 简单处理：如果有标记就分段
    if not bold_runs and not italic_runs:
        # 转义特殊字符
        safe = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;").replace("'", "&apos;")
        safe = safe.replace("\n", '<w:br/>')
        runs_xml = f'<w:r><w:rPr><w:rFonts w:ascii="等线" w:hAnsi="等线" w:eastAsia="等线"/><w:sz w:val="24"/></w:rPr><w:t xml:space="preserve">{safe}</w:t></w:r>'
    else:
        # 分段处理
        segments = []
        last = 0
        all_marks = sorted(set(bold_runs + italic_runs), key=lambda x: (x[0], -x[1]))
        for s, e in all_marks:
            if s > last:
                segments.append((last, s, False, False))
            is_bold = (s, e) in bold_runs
            is_italic = (s, e) in italic_runs
            segments.append((s, e, is_bold, is_italic))
            last = e
        if last < len(text):
            segments.append((last, len(text), False, False))

        for s, e, is_b, is_i in segments:
            seg = text[s:e]
            safe = seg.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;").replace("'", "&apos;")
            safe = safe.replace("\n", '<w:br/>')
            b_str = '<w:b/>' if is_b else ''
            i_str = '<w:i/>' if is_i else ''
            color = 'C00000' if is_b else ('2E75B6' if is_i else '333333')
            runs_xml += f'<w:r><w:rPr>{b_str}{i_str}<w:rFonts w:ascii="等线" w:hAnsi="等线" w:eastAsia="等线"/><w:sz w:val="24"/><w:color w:val="{color}"/></w:rPr><w:t xml:space="preserve">{safe}</w:t></w:r>'

    return f'<w:p><w:pPr><w:pStyle w:val="{style}"/></w:pPr>{runs_xml}</w:p>\n'

